const e = (from: string, type: Edge["type"], to: string, label?: string): Edge => ({ from, to, type, ...(label ? { label } : {}) });
/** Stack chips, in chip order. A tuple gives the chip a different text from the skill label. */
const uses = (project: string, ...skills: (string | [string, string])[]): Edge[] =>
  skills.map((s) => (Array.isArray(s) ? e(project, "uses", `skill-${s[0]}`, s[1]) : e(project, "uses", `skill-${s}`)));
/** Skills the project draws on that the card does not list as chips (they count in the Skill map and the Ask index). */
const alsoUses = (project: string, ...skills: string[]): Edge[] => skills.map((s) => ({ from: project, to: `skill-${s}`, type: "uses", chip: false }));

